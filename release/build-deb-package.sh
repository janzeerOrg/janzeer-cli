#!/usr/bin/env bash
# Wrap the published Linux jz bundle into a Debian/Ubuntu package: build/release/janzeer-cli_<ver>-<rel>_<debarch>.deb
#   release/build-deb-package.sh [--arch amd64|arm64] [--revision N] [--download]
# Same bytes as the tarball on GitHub: with --download the bundle is fetched from the release and checked
# against that release's SHA256SUMS; a local bundle in build/release/ is used as-is (run release/build-cli.sh first).
# Compiles nothing, needs no network at package install time, ships no maintainer scripts.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

DEBARCH=amd64; REVISION=1; DOWNLOAD=0
while [ $# -gt 0 ]; do case "$1" in
  --arch) shift; DEBARCH="$1" ;;
  --revision) shift; REVISION="$1" ;;
  --download) DOWNLOAD=1 ;;
  *) echo "unknown option $1"; exit 2 ;; esac; shift; done
case "$DEBARCH" in
  amd64|x64) DEBARCH=amd64; BARCH=x64 ;;
  arm64|aarch64) DEBARCH=arm64; BARCH=arm64 ;;
  *) echo "unsupported --arch $DEBARCH (want amd64 or arm64)"; exit 2 ;;
esac

for t in dpkg-deb tar sha256sum; do command -v "$t" >/dev/null || { echo "missing $t — sudo apt install dpkg-dev"; exit 1; }; done
VER=$(sed -n 's/^    version = "\(.*\)"/\1/p' build.gradle.kts | head -1)
[ -n "$VER" ] || { echo "version not found in build.gradle.kts"; exit 1; }
REL=build/release; BUNDLE="jz-$VER-linux-$BARCH"; TGZ="$REL/$BUNDLE.tar.gz"
GH="https://github.com/janzeerOrg/janzeer-cli/releases/download/v$VER"
mkdir -p "$REL"

fetch() { # fetch <url> <dest>
  if command -v curl >/dev/null; then curl -fL --retry 5 --retry-all-errors --retry-delay 2 -o "$2" "$1";
  elif command -v wget >/dev/null; then wget -O "$2" "$1";
  else echo "missing curl/wget — needed for --download"; exit 1; fi
}

if [ "$DOWNLOAD" = 1 ] || [ ! -f "$TGZ" ]; then
  if [ "$DOWNLOAD" = 0 ]; then echo "no $TGZ — fetching the release bundle (--download implied)"; fi
  TMPD=$(mktemp -d); trap 'rm -rf "$TMPD"' EXIT
  fetch "$GH/SHA256SUMS" "$TMPD/SHA256SUMS"
  fetch "$GH/$BUNDLE.tar.gz" "$TMPD/$BUNDLE.tar.gz"
  ( cd "$TMPD" && grep "  $BUNDLE.tar.gz\$" SHA256SUMS | sha256sum -c - ) \
    || { echo "$BUNDLE.tar.gz does not match the release SHA256SUMS"; exit 1; }
  cp "$TMPD/$BUNDLE.tar.gz" "$TGZ"
  rm -rf "$TMPD"; trap - EXIT
  echo "downloaded $BUNDLE.tar.gz and verified it against the release SHA256SUMS"
elif [ -f "$REL/SHA256SUMS" ] && grep -q "  $BUNDLE.tar.gz\$" "$REL/SHA256SUMS"; then
  ( cd "$REL" && grep "  $BUNDLE.tar.gz\$" SHA256SUMS | sha256sum -c - )
fi

WORK=$(mktemp -d); trap 'rm -rf "$WORK"' EXIT
tar -xzf "$TGZ" -C "$WORK"
SRC="$WORK/$BUNDLE"
[ -f "$SRC/jz" ] && [ -f "$SRC/LICENSE.txt" ] && [ -f "$SRC/README.txt" ] || { echo "unexpected bundle layout in $TGZ"; exit 1; }

# Shell completions are generated by the packaged binary. A foreign-arch binary cannot run on this
# host, so for a cross build generate them with this host's bundle of the same version instead
# (completion output is architecture-independent text).
case "$(uname -m)" in x86_64|amd64) HOSTARCH=amd64 ;; aarch64|arm64) HOSTARCH=arm64 ;; *) HOSTARCH="" ;; esac
GENBIN="$SRC/jz"
if [ "$DEBARCH" != "$HOSTARCH" ]; then
  HBUNDLE="jz-$VER-linux-$([ "$HOSTARCH" = amd64 ] && echo x64 || echo arm64)"
  if [ -f "$REL/$HBUNDLE.tar.gz" ]; then HTGZ="$REL/$HBUNDLE.tar.gz";
  else fetch "$GH/$HBUNDLE.tar.gz" "$WORK/$HBUNDLE.tar.gz"; HTGZ="$WORK/$HBUNDLE.tar.gz"; fi
  mkdir -p "$WORK/hostbundle"; tar -xzf "$HTGZ" -C "$WORK/hostbundle"
  GENBIN="$WORK/hostbundle/$HBUNDLE/jz"
  echo "cross build ($DEBARCH on $HOSTARCH host): completions generated with the $HOSTARCH bundle of $VER"
fi

PKG="$WORK/pkg"; DEB="janzeer-cli_${VER}-${REVISION}_${DEBARCH}.deb"
mkdir -p "$PKG/DEBIAN" \
         "$PKG/usr/bin" \
         "$PKG/usr/share/doc/janzeer-cli" \
         "$PKG/usr/share/lintian/overrides" \
         "$PKG/usr/share/bash-completion/completions" \
         "$PKG/usr/share/zsh/vendor-completions" \
         "$PKG/usr/share/fish/vendor_completions.d"
install -m 755 "$SRC/jz" "$PKG/usr/bin/jz"
# copyright in the Debian machine-readable form: the bundle's LICENSE.txt is the
# full Apache-2.0 text, which on Debian belongs in /usr/share/common-licenses —
# shipping it verbatim here is a lintian error, so reference it instead.
cat > "$PKG/usr/share/doc/janzeer-cli/copyright" <<EOF
Format: https://www.debian.org/doc/packaging-manuals/copyright-format/1.0/
Upstream-Name: janzeer-cli
Upstream-Contact: Janzeer <janzeeer@proton.me>
Source: https://github.com/janzeerOrg/janzeer-cli

Files: *
Copyright: 2026 Janzeer
License: Apache-2.0

License: Apache-2.0
 Licensed under the Apache License, Version 2.0 (the "License");
 you may not use this file except in compliance with the License.
 You may obtain a copy of the License at
 .
     http://www.apache.org/licenses/LICENSE-2.0
 .
 Unless required by applicable law or agreed to in writing, software
 distributed under the License is distributed on an "AS IS" BASIS,
 WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
 See the License for the specific language governing permissions and
 limitations under the License.
 .
 On Debian systems, the complete text of the Apache License, Version 2.0
 can be found in "/usr/share/common-licenses/Apache-2.0".
EOF
chmod 644 "$PKG/usr/share/doc/janzeer-cli/copyright"
install -m 644 "$SRC/README.txt"  "$PKG/usr/share/doc/janzeer-cli/README.txt"
# Debian changelog for this packaging (version/revision come from the bundle)
{ echo "janzeer-cli ($VER-$REVISION) unstable; urgency=medium"
  echo
  echo "  * Debian/Ubuntu package wrapping the published $VER release binary"
  echo "    (same files as the Arch package; no maintainer scripts)."
  echo
  echo " -- Janzeer <janzeeer@proton.me>  $(date -R)"
} | gzip -9n > "$PKG/usr/share/doc/janzeer-cli/changelog.Debian.gz"
chmod 644 "$PKG/usr/share/doc/janzeer-cli/changelog.Debian.gz"
# The published binary is a GraalVM native image and must not be stripped
# (the Arch package sets !strip for the same reason) — override that one tag.
cat > "$PKG/usr/share/lintian/overrides/janzeer-cli" <<EOF
# The package wraps the published GraalVM native-image binary, which must not
# be stripped; the Arch package (release/packaging/arch/PKGBUILD.in) sets
# options=('!strip' '!debug') for the same binary.
janzeer-cli: unstripped-binary-or-object
EOF
chmod 644 "$PKG/usr/share/lintian/overrides/janzeer-cli"
"$GENBIN" completion bash > "$PKG/usr/share/bash-completion/completions/jz"
"$GENBIN" completion zsh  > "$PKG/usr/share/zsh/vendor-completions/_jz"
"$GENBIN" completion fish > "$PKG/usr/share/fish/vendor_completions.d/jz.fish"
find "$PKG" -type d -exec chmod 755 {} +
chmod 644 "$PKG"/usr/share/bash-completion/completions/jz \
          "$PKG"/usr/share/zsh/vendor-completions/_jz \
          "$PKG"/usr/share/fish/vendor_completions.d/jz.fish
SIZE=$(du -sk --exclude=DEBIAN "$PKG" | cut -f1)
cat > "$PKG/DEBIAN/control" <<EOF
Package: janzeer-cli
Version: $VER-$REVISION
Section: utils
Priority: optional
Architecture: $DEBARCH
Maintainer: Janzeer <janzeeer@proton.me>
Depends: libc6 (>= 2.34), zlib1g
Installed-Size: $SIZE
Homepage: https://janzeer.org
Description: jz — command-line client for the Janzeer blockchain
 jz is the command-line client for the Janzeer blockchain: chain reads,
 live watch, a local encrypted wallet, transactions and node operations.
 This package installs the published release binary; it compiles nothing
 and needs no network at install time.
EOF
dpkg-deb --build --root-owner-group "$PKG" "$REL/$DEB"
grep -v "  $DEB\$" "$REL/SHA256SUMS" > "$REL/SHA256SUMS.tmp" 2>/dev/null || true
( cd "$REL" && sha256sum "$DEB" ) >> "$REL/SHA256SUMS.tmp"; mv "$REL/SHA256SUMS.tmp" "$REL/SHA256SUMS"
rm -rf "$WORK"; trap - EXIT
echo; echo "contents:"; dpkg-deb -c "$REL/$DEB" | sed 's/^/  /'; echo; ls -lh "$REL/$DEB"
